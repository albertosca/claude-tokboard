"""Cycling the period must stay a re-window, never become a reload.

WHY A TIMING ASSERTION IS HERE, WHEN TIMING ASSERTIONS ARE USUALLY A BAD IDEA

Every other test in this suite asks whether the dashboard is CORRECT. All of
them passed while pressing "p" froze the terminal for seconds at a time,
because a headless Pilot waits patiently and a human does not: the defect
was invisible to correctness testing by construction. The shipped bug was
action_cycle_period calling load_data on the event loop, so each press
re-read both JSONL files, re-deduped, re-labelled ~4500 sessions and
re-folded subagent tokens just to show a different slice of records it
already had - 2.1-2.7s of frozen UI per press on the real dataset, enough
that the tmux pane had to be killed and reopened. Responsiveness is the
property that broke, so responsiveness is what has to be asserted; nothing
else in this file's absence would have caught it.

WHAT EACH ASSERTION CAN AND CANNOT CATCH - stated because a check that
cannot fail is worse than no check:

  * the reload counter is the sharp one. It is exact, size-independent and
    cannot flake: during the presses, the data layer must not read the
    JSONL files at all. A return to per-keypress reloading fails it on the
    first press whatever the dataset.
  * the absolute ceiling is the human-facing claim. It is the only one that
    speaks in seconds, and the only one that would catch a NEW blocking
    call (a subprocess, a network read) added to the keypress path.

There used to be a third assertion here: a ratio requiring a re-window to
cost at most half of a full reload. It was deleted (2026-08-18) after
measuring a 33% failure rate over six consecutive runs - see git history
for the exact numbers. On the committed eight-record fixture a full reload
costs under a millisecond, so the "reload" and "re-window" samples it
compared were both sub-millisecond noise dominated by scheduler jitter, GC
pauses and OS-level timer resolution, not by the code path under test; no
amount of raising the threshold fixes a comparison where both operands are
noise. The reload counter above already carries this regression, exactly
and without flaking: it does not matter whether a reload is fast or slow,
only whether it happened, and it fails deterministically on the first
press if action_cycle_period ever goes back to load_data.

The absolute ceiling is deliberately loose: the fixture is eight records,
so on it even a full reload costs about a millisecond and no wall-clock
bound could tell a reload from a re-window. That is a limit of running
hermetically, and it is why the reload counter carries the regression and
the ceiling only carries the "no new second-long work" guarantee. Applied
to the real 4545-session dataset the same 1.5s ceiling would have failed on
the shipped defect (2.19-2.82s per press), which is the calibration that
makes the number a bound and not a decoration.

WHY THIS RUNS IN-PROCESS, AND WHAT THAT DID TO THE CEILING (2026-09-01)

This file used to hand tests/tui_latency_driver.py to .venv/bin/python3,
for the same environment-split reason described at the top of
tests/test_tui_state.py, and coverage.py could not see into that child.
Driving the app in this process instead puts dashboard_tui.py back under
measurement - and puts the keypress path under coverage instrumentation,
which the subprocess never was. So the ceiling had to be re-checked rather
than assumed, against a dataset the size the ceiling was calibrated for
rather than against the eight-record fixture.

Measured 2026-09-01 on this machine, in-process, over a CONSTRUCTED
4,500-session dataset (generated by the probe from a seeded RNG - the real
~/.claude/metrics was never read), five runs per mode, five "p" presses
per run, the two modes interleaved so they meet the same machine load:

                     worst press    mean press
    uninstrumented      0.498 s       0.290 s
    instrumented        0.463 s       0.269 s
    ceiling             1.5   s

The two distributions overlap completely: on this Python (3.14, where
coverage uses the sys.monitoring backend) instrumentation costs less than
the run-to-run scheduler noise, and neither mode is reliably the slower
one. The worst instrumented press ever observed is 3.2x inside the
ceiling.

DECISION: the margin holds, the ceiling is unchanged at 1.5s, and the
latency test stays fully under coverage measurement - no exemption, so
none of the 409 arcs the former latency driver contributed is lost. The
ceiling was NOT adjusted: it is the same number, re-justified against a
dataset the size it was calibrated for and against an instrument the
original calibration never ran under.

One warning for whoever re-runs this probe. Its FIRST five paired runs
reported coverage as free, and they were wrong: the probe passed
`source=[".../dashboard_tui.py"]` to coverage.Coverage, and a FILE PATH in
`source` traces nothing and only emits a module-not-imported warning. The
module being timed was not instrumented at all in the runs that concluded
instrumentation was cheap. The numbers above come from module-name spelling
(`source=["dashboard_tui", ...]`, what --cov=dashboard_tui resolves to)
and were only trusted after asserting the collected data was non-empty:
326 lines and 420 arcs traced. A timing comparison whose "instrumented"
arm is not instrumented cannot distinguish its two answers.

The presses this file actually times still run against the committed
eight-record fixture, deliberately - test_the_measurement_used_the_fixture
_and_not_the_real_data below is what proves it, and the numbers above are
the evidence that the ceiling is not thereby measuring an unrepresentative
best case.
"""

import asyncio
import sys
import time
from pathlib import Path
from typing import Any

import pytest

# Same path setup, and same reason, as tests/test_tui_state.py - stated
# here too rather than relying on that module's import having run first,
# so this file's imports do not depend on collection order.
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "lib"))
sys.path.insert(0, str(REPO_ROOT))

import metrics_core as mr  # noqa: E402
from test_fixture_isolation import EXPECTED_MEMBERSHIP  # noqa: E402
from test_tui_state import seeded_tui_home  # noqa: E402

import dashboard_tui as tui  # noqa: E402

# A press must finish well inside this. Roughly half the shipped defect's
# real-data latency, and (see the module docstring) 3.2x the slowest
# instrumented press measured over a constructed 4,500-session dataset on
# 2026-09-01. Loose enough to survive a busy machine and still name the
# failure.
MAX_PRESS_SECONDS = 1.5


async def _drive_period_cycle() -> dict[str, Any]:
    """Everything is measured inside one process, on one machine, under one
    load, so the numbers are comparable to each other even when the machine
    is busy:

      presses      wall time of the whole key round-trip, recompose
                   included - what the human waits for.
      load_records the number of times the data layer re-read the JSONL
                   files during the presses. Zero is the only correct
                   answer.
    """
    args = tui.build_arg_parser().parse_args(["--label-budget", "0"])
    data = tui.load_data(args, mr=mr)
    app = tui.MetricsTUIApp(mr, data, args=args)

    presses: list[float] = []
    periods: list[Any] = []
    records_seen: list[int] = []
    reload_count = {"n": 0}
    async with app.run_test(size=(140, 45)) as pilot:
        await pilot.pause()

        # Counted only from here on, so the startup load above is not
        # mistaken for a reload triggered by a keypress.
        real_load_records = mr.load_records

        def counting_load_records(path: str) -> list[dict[str, Any]]:
            reload_count["n"] += 1
            return real_load_records(path)

        mr.load_records = counting_load_records
        try:
            for _ in range(len(mr.PERIODS)):
                started = time.perf_counter()
                await pilot.press("p")
                await pilot.pause()
                presses.append(time.perf_counter() - started)
                periods.append(app.data["period_id"])
                records_seen.append(len(app.data["records"]))
        finally:
            mr.load_records = real_load_records

    return {
        "presses": presses,
        "periods": periods,
        "load_records_calls_during_presses": reload_count["n"],
        "records_per_period": dict(zip(periods, records_seen, strict=True)),
    }


@pytest.fixture(scope="session")
def cycle_timings(tmp_path_factory: pytest.TempPathFactory) -> Any:
    """Drives the app against a throwaway HOME seeded with the committed
    fixture, so this measures the fixture and never the real
    ~/.claude/metrics. See seeded_tui_home for why setenv("HOME") alone
    would not be enough now that this runs in-process."""
    mp = pytest.MonkeyPatch()
    try:
        seeded_tui_home(mp, tmp_path_factory.mktemp("tui-latency-home"))
        return asyncio.run(_drive_period_cycle())
    finally:
        mp.undo()


def test_the_period_actually_cycles(cycle_timings):
    """Guards the timings above from the cheapest way to pass them: an
    action that does nothing at all is instantaneous AND reads no files."""
    assert cycle_timings["periods"] == ["ontem", "desde-segunda", "15-dias", "mes", "tudo"], (
        f"pressing 'p' produced {cycle_timings['periods']} - the cycle order changed, "
        "or a press did not land"
    )
    seen = cycle_timings["records_per_period"]
    # Only the windows that are anchored to today, never to the calendar
    # week: "desde-segunda" spans one day on a Monday and seven on a Sunday.
    for period, ids in EXPECTED_MEMBERSHIP.items():
        assert seen[period] == len(ids), (
            f"{period} showed {seen[period]} records, not {len(ids)} - the re-windowed view "
            "no longer matches the window"
        )


def test_cycling_the_period_never_re_reads_the_data(cycle_timings):
    """The regression itself: the period changes what is DISPLAYED, and the
    raw data does not change between periods, so a press has no business
    going back to disk."""
    assert cycle_timings["load_records_calls_during_presses"] == 0, (
        f"pressing 'p' re-read the metrics files "
        f"{cycle_timings['load_records_calls_during_presses']} time(s). The period-independent "
        "work belongs in load_base_data, once, at startup - see apply_period"
    )


def test_every_press_stays_responsive(cycle_timings):
    slowest = max(cycle_timings["presses"])
    assert slowest < MAX_PRESS_SECONDS, (
        f"the slowest 'p' press took {slowest:.2f}s (ceiling {MAX_PRESS_SECONDS}s). "
        f"All presses: {[round(p, 3) for p in cycle_timings['presses']]}"
    )


def test_the_measurement_used_the_fixture_and_not_the_real_data(cycle_timings):
    """The timings are only meaningful if they came from the eight-record
    fixture; against the real dataset this file would measure something
    else entirely and its numbers would drift daily."""
    assert cycle_timings["records_per_period"]["tudo"] == len(EXPECTED_MEMBERSHIP["tudo"]), (
        f"the app saw {cycle_timings['records_per_period']['tudo']} sessions under 'tudo' - "
        "that is not the fixture, so HOME was not isolated"
    )
